import crypto from 'crypto'

import type { SanitizedCollectionConfig } from '../collections/config/types.js'
import type { JsonObject, PayloadRequest } from '../types/index.js'

import { ValidationError } from '../errors/index.js'

const serverGeneratedAPIKeyRequests = new WeakSet<PayloadRequest>()

/** Generates a random API key for explicit key rotations. */
export const generateAPIKey = (): string => crypto.randomUUID()

/** Generates a stable API key so it can be revealed before its document is saved. */
export const generateAPIKeyFromSeed = ({
  secret,
  seed,
}: {
  secret: string
  seed: string
}): string => {
  const bytes = crypto
    .createHmac('sha256', secret)
    .update(`payload:api-key:${seed}`)
    .digest()
    .subarray(0, 16)

  bytes[6] = (bytes[6]! & 0x0f) | 0x40
  bytes[8] = (bytes[8]! & 0x3f) | 0x80

  const hex = bytes.toString('hex')

  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`
}

/** Returns whether the request is assigning an API key generated by Payload. */
export const isServerGeneratedAPIKeyRequest = (req: PayloadRequest): boolean =>
  serverGeneratedAPIKeyRequests.has(req)

/** Allows API key assignment while Payload persists a server-generated key. */
export const withServerGeneratedAPIKey = async <T>(
  req: PayloadRequest,
  callback: () => Promise<T>,
): Promise<T> => {
  serverGeneratedAPIKeyRequests.add(req)

  try {
    return await callback()
  } finally {
    serverGeneratedAPIKeyRequests.delete(req)
  }
}

/** Prevents API key assignment outside trusted server and Local API requests. */
export const assertAPIKeyAssignment = ({
  collection,
  data,
  overrideAccess,
  req,
}: {
  collection: SanitizedCollectionConfig
  data: JsonObject
  overrideAccess?: boolean
  req: PayloadRequest
}): void => {
  const isAPIKeyAssignment =
    collection.auth?.useAPIKey &&
    Object.prototype.hasOwnProperty.call(data, 'apiKey') &&
    data.apiKey !== undefined

  const canAssignAPIKey =
    (req.payloadAPI === 'local' && overrideAccess === true) || isServerGeneratedAPIKeyRequest(req)

  if (!isAPIKeyAssignment || canAssignAPIKey) {
    return
  }

  throw new ValidationError(
    {
      collection: collection.slug,
      errors: [
        {
          message:
            'API keys can only be assigned through the Local API when overrideAccess is enabled.',
          path: 'apiKey',
        },
      ],
      req,
    },
    req.t,
  )
}
