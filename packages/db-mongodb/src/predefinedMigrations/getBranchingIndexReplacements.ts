import type { IndexDescriptionInfo } from 'mongodb'
import type { IndexDefinition, IndexOptions } from 'mongoose'
import type { Payload, SanitizedCollectionConfig } from 'payload'

import { isDeepStrictEqual } from 'node:util'
import { branchDocIDField, branchField } from 'payload'

import type { CollectionModel } from '../types.js'

import { buildSchema } from '../models/buildSchema.js'

type LegacyIndex = {
  fields: IndexDefinition
  options: IndexOptions
}

/** Identifies legacy constraints without treating every index absent from the schema as obsolete. */
export const getBranchingIndexReplacements = async ({
  collection,
  model,
  payload,
}: {
  collection: SanitizedCollectionConfig
  model: CollectionModel
  payload: Payload
}): Promise<{ indexName: string; model: CollectionModel }[]> => {
  const legacyIndexes: LegacyIndex[] = model.schema.indexes().flatMap(([fields, options]) => {
    if (!options.unique || !(branchField in fields) || branchDocIDField in fields) {
      return []
    }

    return [{ fields: withoutBranch({ fields }), options }]
  })

  // Before branching, localized compound indexes without requireExists combined all locales.
  // Rebuild that key pattern rather than assuming it was one index per locale.
  const legacyCompoundSchema = buildSchema({
    buildSchemaOptions: {},
    compoundIndexes: collection.sanitizedIndexes
      .filter(
        (index) =>
          index.unique &&
          index.fields.some(({ path }) => path === branchField) &&
          !index.fields.some(({ path }) => path === branchDocIDField),
      )
      .map((index) => ({
        ...index,
        fields: index.fields.filter(({ path }) => path !== branchField),
      })),
    configFields: [],
    payload,
  })

  legacyIndexes.push(
    ...legacyCompoundSchema.indexes().map(([fields, options]) => ({ fields, options })),
  )

  if (!legacyIndexes.length) {
    return []
  }

  const indexes = await model.collection.indexes()
  const replacements = []

  for (const index of indexes) {
    if (!index.name || index.name === '_id_' || !index.unique) {
      continue
    }

    const legacy = legacyIndexes.find(({ fields }) =>
      hasSameKeys({ first: fields, second: index.key }),
    )

    if (!legacy) {
      continue
    }

    if (!isLegacyIndex({ index, legacy, model })) {
      payload.logger.warn({
        msg: `Preserving index "${index.name}" on "${model.collection.name}": its custom options do not match a legacy branching index. Review this constraint before using branches.`,
      })
      continue
    }

    replacements.push({ indexName: index.name, model })
  }

  return replacements
}

const withoutBranch = ({ fields }: { fields: IndexDefinition }): IndexDefinition =>
  Object.fromEntries(Object.entries(fields).filter(([path]) => path !== branchField))

const hasSameKeys = ({
  first,
  second,
}: {
  first: Record<string, unknown>
  second: Record<string, unknown>
}): boolean => isDeepStrictEqual(Object.entries(first), Object.entries(second))

const isLegacyIndex = ({
  index,
  legacy,
  model,
}: {
  index: IndexDescriptionInfo
  legacy: LegacyIndex
  model: CollectionModel
}): boolean => {
  const knownOptions = new Set([
    'background',
    'collation',
    'key',
    'name',
    'ns',
    'partialFilterExpression',
    'sparse',
    'unique',
    'v',
  ])

  if (Object.keys(index).some((option) => !knownOptions.has(option))) {
    return false
  }

  // Payload field-level unique indexes can be sparse (drafts, localization, optional fields).
  // Sparse compound indexes and custom partial filters are not generated by that path.
  if (index.sparse && Object.keys(legacy.fields).length !== 1) {
    return false
  }

  if (
    index.partialFilterExpression &&
    !isDeepStrictEqual(index.partialFilterExpression, legacy.options.partialFilterExpression)
  ) {
    return false
  }

  // MongoDB expands non-simple collations in listIndexes. Without an exact known definition,
  // preserve the index rather than guessing that a custom collation is safe to remove.
  return !index.collation && !model.schema.options.collation
}
