import type { ImportMap, SanitizedConfig, ServerFunctionClient } from 'payload'

import React, { Suspense } from 'react'

import type { InitAdminContextFn } from '../../views/Root/index.js'

// eslint-disable-next-line payload/no-imports-from-exports-dir -- Server component must reference client bundle for proper client boundary in production
import { DocumentRoot, RootProviders } from '../../exports/client/index.js'
import { checkDependencies, type CheckDependenciesArgs } from '../../utilities/checkDependencies.js'
import { getRootLayoutData } from '../../utilities/getRootLayoutData.js'
import { NestProviders } from './NestProviders.js'
import { getViewportMeta } from './viewport.js'
// eslint-disable-next-line payload/no-imports-from-self -- Self-import ensures the consumer bundler resolves the full CSS chain
import '@payloadcms/ui/css/app.css'

type Font = {
  className?: string
  variable?: string
}

export const metadata = {
  description: 'Generated by Next.js',
  title: 'Next.js',
}

type RootLayoutProps = {
  /**
   * Framework-specific peer-dependency version constraints, merged on top of the
   * universal React/react-dom checks. Each framework adapter supplies its own
   * (e.g. Next.js passes `{ dependencyVersions: { next: { version: '>=15.0.0' } } }`).
   */
  readonly additionalDependencyChecks?: CheckDependenciesArgs
  readonly children: React.ReactNode
  readonly config: Promise<SanitizedConfig>
  /**
   * Fonts to apply to the admin `<html>` element. Each entry's
   * `variable ?? className` is appended to the `<html>` class list.
   * Framework-specific font loaders (e.g. `next/font`) are supplied by the caller.
   */
  readonly fonts?: Font[]
  /**
   * Custom content to render inside the admin panel's `<head>` element.
   *
   * Use this to inject scripts, meta tags, or links — for example, analytics
   * snippets via `next/script`, custom favicons, or preconnect hints.
   *
   * @example
   * ```tsx
   * import Script from 'next/script'
   *
   * <RootLayout
   *   head={<Script src="https://example.com/analytics.js" strategy="afterInteractive" />}
   *   {...rest}
   * />
   * ```
   */
  readonly head?: React.ReactNode
  readonly htmlProps?: React.HtmlHTMLAttributes<HTMLHtmlElement>
  readonly importMap: ImportMap
  readonly initAdminContext: InitAdminContextFn
  /**
   * Client router adapter. Caller supplies a framework-specific provider
   * (for Next.js use the `NextRouterAdapter` exported from `@payloadcms/next`).
   */
  readonly RouterAdapter: React.FC<{ children: React.ReactNode }>
  readonly serverFunction: ServerFunctionClient
}

export const RootLayout = (props: RootLayoutProps) => {
  checkDependencies(props.additionalDependencyChecks)

  const content = <RootLayoutContent {...props} />

  if (process.env.PAYLOAD_CACHE_COMPONENTS_ENABLED === 'true') {
    return <Suspense fallback={null}>{content}</Suspense>
  }

  return content
}

const RootLayoutContent = async ({
  children,
  config: configPromise,
  fonts = [],
  head,
  htmlProps = {},
  importMap,
  initAdminContext,
  RouterAdapter,
  serverFunction,
}: RootLayoutProps) => {
  const context = await initAdminContext({ configPromise, importMap, key: 'RootLayout' })
  const { permissions, req, user } = context
  const { config } = req.payload
  const data = await getRootLayoutData({ context, importMap })

  return (
    <DocumentRoot
      dir={data.dir}
      fonts={fonts}
      head={head}
      highContrastMode={data.highContrastMode}
      htmlProps={htmlProps}
      languageCode={data.languageCode}
      suppressHydrationWarning={data.suppressHydrationWarning}
      theme={data.theme}
      viewport={getViewportMeta(context.headers.get('user-agent') ?? undefined)}
    >
      <RootProviders data={data} RouterAdapter={RouterAdapter} serverFunction={serverFunction}>
        {Array.isArray(config.admin?.components?.providers) &&
        config.admin.components.providers.length > 0 ? (
          <NestProviders
            importMap={req.payload.importMap}
            providers={config.admin.components.providers}
            serverProps={{
              i18n: req.i18n,
              payload: req.payload,
              permissions,
              server: req.server,
              user,
            }}
          >
            {children}
          </NestProviders>
        ) : (
          children
        )}
      </RootProviders>
    </DocumentRoot>
  )
}
