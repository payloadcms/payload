#!/usr/bin/env node
/**
 * Packs this branch's Payload packages (packages/*) into tarballs and points the cms app at
 * them through pnpm `overrides`, so the app runs the code on this branch instead of the
 * versions published to npm. This mirrors how Payload's CI builds templates against local
 * packages (tools/scripts/src/build-template-with-local-pkgs.ts).
 *
 * The packages must be built first (their `dist` folders are what gets packed):
 *   pnpm turbo build --filter payload --filter @payloadcms/next ...   (see Dockerfile)
 *
 * Usage (from anywhere):
 *   node apps/cms/scripts/pack-local-packages.mjs
 *
 * Writes the tarballs to apps/cms/local-packages/ and the overrides to
 * apps/cms/pnpm-workspace.yaml. Run `pnpm install` in apps/cms afterwards.
 */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

/** Every workspace package the app needs at runtime, including transitive ones. */
const PACKAGE_DIRS = [
  'db-mongodb',
  'graphql',
  'next',
  'payload',
  'plugin-cloud-storage',
  'richtext-lexical',
  'storage-s3',
  'transformer-sharp',
  'translations',
  'ui',
]

const OVERRIDES_MARKER = '# --- generated by scripts/pack-local-packages.mjs ---'

const appDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const repoRoot = path.resolve(appDir, '../..')
const tarballDir = path.join(appDir, 'local-packages')

main()

function main() {
  fs.rmSync(tarballDir, { force: true, recursive: true })
  fs.mkdirSync(tarballDir, { recursive: true })

  const overrides = {}

  for (const packageDir of PACKAGE_DIRS) {
    const packagePath = path.join(repoRoot, 'packages', packageDir)
    const { name, version } = JSON.parse(
      fs.readFileSync(path.join(packagePath, 'package.json'), 'utf8'),
    )

    if (!fs.existsSync(path.join(packagePath, 'dist'))) {
      throw new Error(`${name} has no dist folder - build the packages before packing them.`)
    }

    execFileSync('pnpm', ['pack', '--pack-destination', tarballDir], {
      cwd: packagePath,
      stdio: ['ignore', 'ignore', 'inherit'],
    })

    // pnpm names tarballs `<scope>-<name>-<version>.tgz`, e.g. payloadcms-ui-4.0.0.tgz
    const tarballName = `${name.replace(/^@/, '').replace('/', '-')}-${version}.tgz`

    if (!fs.existsSync(path.join(tarballDir, tarballName))) {
      throw new Error(`Expected pnpm to create ${tarballName} in ${tarballDir}`)
    }

    overrides[name] = `file:./local-packages/${tarballName}`
    console.log(`packed ${name}@${version}`)
  }

  writeOverrides({ overrides })
}

/**
 * Replaces the generated `overrides` block at the end of the app's pnpm-workspace.yaml.
 * Overrides apply to direct and transitive dependencies, so both `payload` in package.json and
 * e.g. `@payloadcms/translations` required by `@payloadcms/ui` resolve to the local tarballs.
 */
function writeOverrides({ overrides }) {
  const workspaceFile = path.join(appDir, 'pnpm-workspace.yaml')
  const existing = fs.readFileSync(workspaceFile, 'utf8').split(OVERRIDES_MARKER)[0].trimEnd()

  const lines = [
    existing,
    '',
    OVERRIDES_MARKER,
    'overrides:',
    ...Object.entries(overrides).map(([name, spec]) => `  '${name}': '${spec}'`),
    '',
  ]

  fs.writeFileSync(workspaceFile, lines.join('\n'))
  console.log(`wrote ${Object.keys(overrides).length} overrides to ${workspaceFile}`)
}
